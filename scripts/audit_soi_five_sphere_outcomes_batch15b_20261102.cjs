'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const current=JSON.parse(fs.readFileSync('data/soi-five-sphere-outcomes-batch15-independent-vs-primary-20261102.json','utf8'));
const prior=JSON.parse(fs.readFileSync('data/soi-five-sphere-verified-outcomes-batch15-20261102.json','utf8'));
assert.equal(current.count,15);
assert.equal(current.observations.length,15);
assert.equal(current.policy.auditCompleted,20);
assert.equal(current.policy.auditTotal,30);
assert.equal(current.policy.gatePromotion,false);
assert.equal(current.policy.researchOnly,true);
assert.equal(current.policy.uiTouched,false);
assert.equal(current.policy.causalAttribution,'not_established');
assert.deepEqual(Object.keys(current.policy.influenceScores).sort(),['china','eu','india','russia','us']);
assert.ok(Object.values(current.policy.influenceScores).every(x=>x===null));
const ids=current.observations.map(x=>x.id);
assert.equal(new Set(ids).size,15);
const priorIds=new Set(prior.observations.map(x=>x.id));
assert.ok(ids.every(x=>!priorIds.has(x)),'No repeat observations from earlier merged batch');
const counts={};
for(const o of current.observations){
  counts[o.sphere]=(counts[o.sphere]||0)+1;
  assert.ok(o.id&&o.metric&&o.period&&o.unit&&o.comparison);
  assert.ok(Number.isFinite(o.value),'Numeric observation must be finite: '+o.id);
  assert.ok(o.limitation&&o.costGap&&o.counterfactualGap,'Cost/counterfactual explicitly tracked: '+o.id);
  assert.equal(o.causalAttribution,null);
  assert.equal(o.measurementStatus,'observed_or_reported_actual');
  const src=current.sources[o.sourceKey];
  assert.ok(src&&src.url.startsWith('https://')&&src.publisher);
  assert.equal(o.independentThirdParty,src.independentOfActor,'Never label official self-report as independent corroboration');
  if(o.components)for(const c of o.components)assert.ok(Number.isFinite(c.value)&&c.unit);
}
assert.deepEqual(counts,{us:3,eu:4,china:3,russia:3,india:2});
assert.ok(current.nonAdditivity.length>=7);
const find=id=>current.observations.find(x=>x.id===id);
assert.ok(find('RUSSIA-2026-09-LNG-EXPORT-GROSS').value<find('RUSSIA-2026-09-FOSSIL-EXPORT-GROSS').value);
assert.ok(find('CHINA-2025-FOSSIL-GENERATION-CHANGE').value<0,'Negative physical change must not be suppressed');
assert.equal(find('EU-2026-10-UKRAINE-FACILITY-CASH').components[0].value,0.8);
assert.ok(find('EU-2025-ENERGY-IMPORT-VALUE').vintageMismatchFlag);
assert.ok(find('EU-2025-ENERGY-IMPORT-MASS').vintageMismatchFlag);
assert.ok(find('US-INDIA-2025-SERVICES-TRADE').components.reduce((s,x)=>s+x.value,0)-90.4<0.11,'USTR component rounding acknowledged');
assert.ok(find('INDIA-FY2025-26-SOLAR-CAPACITY-ADDED').period.includes('2026-01-31'));
console.log('15 distinct five-sphere observed measurements audited; provenance, period, cost and causal gates intact');
