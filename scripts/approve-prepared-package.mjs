import fs from 'node:fs';
import assert from 'node:assert/strict';
import {sha256} from './validate-publication-package.mjs';
const [file,expected,slug,mode,out]=process.argv.slice(2);
assert(['test','production'].includes(mode),'Invalid mode');
assert(/^[a-z0-9-]{1,120}$/.test(slug),'Invalid slug');
assert(mode==='test'?slug.startsWith('isolated-preflight-test-'):!slug.startsWith('isolated-preflight-test-'),'Test/production separation');
const bytes=fs.readFileSync(file);
assert(/^[a-f0-9]{64}$/.test(expected)&&sha256(bytes)===expected,'Review package hash mismatch');
const p=JSON.parse(bytes);
assert(p.slug===slug&&p.evidence.slug===slug,'Slug mismatch');
assert(p.publisher_approved===false&&p.evidence.publisher_approved===false&&p.evidence.image.publisher_approved===false,'Expected unapproved package');
assert(sha256(p.article)===p.evidence.article_sha256,'Article hash mismatch');
assert(p.image_import.sha256===p.evidence.image.sha256,'Image hash mismatch');
assert(p.reel==null,'Website only');
p.publisher_approved=true;p.evidence.publisher_approved=true;p.evidence.image.publisher_approved=true;
if(mode==='test')p.dry_run=true;
fs.writeFileSync(out,JSON.stringify(p),{flag:'wx'});
console.log('Exact reviewed article preserved; '+mode+' approval envelope generated');
