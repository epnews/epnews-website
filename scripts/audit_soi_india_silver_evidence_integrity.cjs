const fs=require('node:fs');
const assert=require('node:assert/strict');
const d=JSON.parse(fs.readFileSync('data/soi-diplomatic-audit-worklist.json','utf8'));
const s=d.indiaSilverPostShockCrosscheck;
assert.ok(s,'missing silver post-shock evidence');
assert.equal(s.gateCompleted,false);
assert.equal(s.scoreAuthorized,false);
assert.equal(s.evidence.length,11);
const lookup=(name,period)=>s.evidence.find(x=>x.indicator===name&&x.period===period);
const imports=lookup('India total silver imports','2025');
const region=lookup('Middle East bullion exports','2025');
const uk=lookup('UK share of India silver imports','2025');
const hk=lookup('Hong Kong share of India silver imports','2025');
const grain24=lookup('Silver grain share of India silver imports','2024');
const grain25=lookup('Silver grain share of India silver imports','2025');
assert.equal(imports.value,7222);
assert.equal(region.value,480);
assert.equal(uk.value,40);
assert.equal(hk.value,30);
assert.equal(grain24.value-grain25.value,30);
assert.ok(uk.value+hk.value<=100);
assert.notEqual(imports.indicator,region.indicator,'regional exports cannot be relabeled national imports');
assert.ok(region.limitation.includes('not India-UAE bilateral'));
assert.ok(imports.limitation.includes('All-origin'));
const pre=lookup('Silver imported via UAE CEPA','Jan–Feb 2024');
const uae=lookup('Silver imports from UAE','Jan–May 2024');
assert.ok(pre&&uae);
assert.notEqual(pre.period,uae.period,'different windows cannot be directly compared');
assert.ok(uae.limitation.includes('not necessarily all preference claims'));
for(const row of s.evidence){assert.ok(row.source.startsWith('https://'));assert.ok(row.limitation.length>=35);assert.ok(row.period);assert.ok(row.unit);}
assert.ok(s.causalInterpretation.includes('unestimated'));
console.log('India silver evidence integrity checks passed; attribution and scoring remain gated');
